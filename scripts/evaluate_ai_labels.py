"""Compare theme classifiers against provisional AI-assisted labels.

IMPORTANT: These reference labels were generated by an AI assistant and were
not independently human-verified. Results are agreement diagnostics,
NOT validated accuracy or scientific performance estimates.
"""

from pathlib import Path
import pandas as pd
from sklearn.metrics import f1_score

ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "data" / "manual_label_completed_ai_assisted.csv"
OUTPUT = ROOT / "data" / "ai_assisted_label_comparison.csv"
MATRIX = ROOT / "data" / "ai_assisted_v2_confusion_matrix.csv"
REPORT = ROOT / "docs" / "AI_ASSISTED_LABEL_COMPARISON.md"


def main():
    if not INPUT.is_file():
        raise FileNotFoundError(f"Missing input CSV: {INPUT}")

    df = pd.read_csv(INPUT, keep_default_na=True)
    needed = ["review_id", "review", "baseline_theme", "semantic_theme", "assistant_label"]
    missing = [c for c in needed if c not in df.columns]
    if missing:
        raise ValueError(f"CSV missing expected columns: {missing}")

    for c in needed:
        if df[c].isna().any() or (df[c].astype(str).str.strip() == "").any():
            raise ValueError(f"Column {c} contains missing or blank values")

    if df["review_id"].duplicated().any():
        raise ValueError("The label file has duplicate review IDs")

    y = df["assistant_label"].astype(str).str.strip()
    old = df["baseline_theme"].astype(str).str.strip()
    new = df["semantic_theme"].astype(str).str.strip()
    labels = sorted(set(y) | set(old) | set(new))

    n = len(df)
    old_match = old.eq(y)
    new_match = new.eq(y)
    old_agreement = old_match.mean()
    new_agreement = new_match.mean()
    old_macro_f1 = f1_score(y, old, labels=labels, average="macro", zero_division=0)
    new_macro_f1 = f1_score(y, new, labels=labels, average="macro", zero_division=0)

    result = df.copy()
    result["baseline_matches_ai_label"] = old_match
    result["v2_matches_ai_label"] = new_match
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    result.to_csv(OUTPUT, index=False, encoding="utf-8")

    cm = pd.crosstab(y.rename("AI reference label"), new.rename("V2 predicted label"))
    cm = cm.reindex(index=labels, columns=labels, fill_value=0)
    cm.to_csv(MATRIX, encoding="utf-8")

    summary = "# Preliminary model comparison (AI-assisted labels)\n\n"
    summary += (
        "**Important:** All reference labels in this file were produced with AI assistance. "
        "They have **not** been independently reviewed by a human. "
        "The results below are model-to-AI-label agreement diagnostics, "
        "**not validated accuracy, precision, or F1 against human ground truth**.\n\n"
        f"- Reviews in evaluation file: **{n}**\n"
        f"- Baseline exact agreement: **{int(old_match.sum())}/{n} ({old_agreement:.1%})**\n"
        f"- Semantic V2 exact agreement: **{int(new_match.sum())}/{n} ({new_agreement:.1%})**\n"
        f"- Baseline macro F1 vs AI-assisted labels: **{old_macro_f1:.3f}**\n"
        f"- Semantic V2 macro F1 vs AI-assisted labels: **{new_macro_f1:.3f}**\n\n"
        "## Interpretation\n\n"
        "These are exploratory diagnostics only. The sample contains 60 comments and "
        "is too small to establish reliable per-category performance. "
        "The `Other / General` label is broad, and taxonomy mismatches can affect scores. "
        "The same AI that suggested labels may share biases with the classifier.\n\n"
        "## Next validation steps\n\n"
        "1. Independently human-review a larger stratified sample; record labeling rules and ambiguous cases.\n"
        "2. Compare class-wise precision, recall, and F1 using confirmed labels.\n"
        "3. Tune thresholds on a separate development set and evaluate once on a held-out set.\n\n"
        "Files: `data/ai_assisted_label_comparison.csv`, "
        "`data/ai_assisted_v2_confusion_matrix.csv`.\n"
    )
    REPORT.parent.mkdir(parents=True, exist_ok=True)
    REPORT.write_text(summary, encoding="utf-8")

    print("\n=== Preliminary AI-Assisted Label Comparison ===")
    print(f"Reviews: {n}")
    print(f"Baseline agreement: {old_match.sum()}/{n} ({old_agreement:.1%})")
    print(f"V2 agreement: {new_match.sum()}/{n} ({new_agreement:.1%})")
    print(f"Baseline macro F1 vs AI labels: {old_macro_f1:.3f}")
    print(f"V2 macro F1 vs AI labels: {new_macro_f1:.3f}")
    print("IMPORTANT: AI reference labels were not human-validated.")
    print(f"Saved comparison: {OUTPUT}")
    print(f"Saved confusion table: {MATRIX}")
    print(f"Saved notes: {REPORT}")


if __name__ == "__main__":
    main()
